/// A titled paragraph block of a legal text.
class LegalSection {
  const LegalSection(this.title, this.paragraphs);

  final String title;
  final List<String> paragraphs;
}

/// Privacy policy in the active language.
abstract final class PrivacyText {
  static String get intro =>
      L10n.isEnglish ? PrivacyTextEn.intro : PrivacyTextDe.intro;

  static List<LegalSection> get sections =>
      L10n.isEnglish ? PrivacyTextEn.sections : PrivacyTextDe.sections;

  static String get updated =>
      L10n.isEnglish ? PrivacyTextEn.updated : PrivacyTextDe.updated;
}

